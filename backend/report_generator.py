import os
import logging
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors

logging.basicConfig(level=logging.INFO, format="%(asctime)s - %(levelname)s - %(message)s")
logger = logging.getLogger(__name__)

def generate_individual_prediction_pdf(student_data: dict, prediction_res: dict, output_filepath: str) -> str:
    """
    Generates a PDF report for a student placement prediction.
    """
    os.makedirs(os.path.dirname(output_filepath), exist_ok=True)
    doc = SimpleDocTemplate(output_filepath, pagesize=letter, leftMargin=36, rightMargin=36, topMargin=36, bottomMargin=36)
    styles = getSampleStyleSheet()

    # Custom styles
    title_style = ParagraphStyle(
        'HeaderTitle',
        parent=styles['Heading1'],
        fontSize=22,
        textColor=colors.HexColor('#0f172a'),
        alignment=0,
        spaceAfter=4
    )
    subtitle_style = ParagraphStyle(
        'HeaderSubtitle',
        parent=styles['Normal'],
        fontSize=10,
        textColor=colors.HexColor('#64748b'),
        alignment=0,
        spaceAfter=15
    )
    section_heading = ParagraphStyle(
        'SectionHeading',
        parent=styles['Heading2'],
        fontSize=14,
        textColor=colors.HexColor('#1e293b'),
        spaceBefore=10,
        spaceAfter=8
    )

    story = []

    # Header
    story.append(Paragraph("AI Placement Intelligence & Assessment Report", title_style))
    story.append(Paragraph(f"Generated by Placement Intelligence System | Candidate: <b>{student_data.get('Name', 'Student')}</b>", subtitle_style))
    story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor('#2563eb'), spaceAfter=15))

    # Prediction Summary Box
    status = prediction_res.get('placement_status', 'Unknown')
    prob = prediction_res.get('placement_probability', 0.0)
    risk = prediction_res.get('risk_level', 'Medium')
    conf = prediction_res.get('confidence_score', 0.0)

    status_color = "#16a34a" if status == "Placed" else "#dc2626"

    summary_table_data = [
        [
            Paragraph(f"<b>Prediction Status:</b> <font color='{status_color}'><b>{status.upper()}</b></font>", styles['Normal']),
            Paragraph(f"<b>Placement Probability:</b> {prob}%", styles['Normal'])
        ],
        [
            Paragraph(f"<b>Risk Level:</b> {risk}", styles['Normal']),
            Paragraph(f"<b>Model Confidence:</b> {conf}%", styles['Normal'])
        ]
    ]
    summary_table = Table(summary_table_data, colWidths=[270, 270])
    summary_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#f8fafc')),
        ('PADDING', (0, 0), (-1, -1), 10),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1')),
    ]))
    story.append(summary_table)
    story.append(Spacer(1, 15))

    # Student Profile Table
    story.append(Paragraph("Student Profile Summary", section_heading))
    profile_data = [
        ["Degree", str(student_data.get("Degree", "-")), "Branch", str(student_data.get("Branch", "-"))],
        ["CGPA", str(student_data.get("CGPA", "-")), "Backlogs", str(student_data.get("Backlogs", 0))],
        ["Internships", str(student_data.get("Internships", 0)), "Projects", str(student_data.get("Projects", 0))],
        ["Coding Skills (1-10)", str(student_data.get("Coding_Skills", "-")), "Communication Skills", str(student_data.get("Communication_Skills", "-"))],
        ["Aptitude Score", str(student_data.get("Aptitude_Test_Score", "-")), "Certifications", str(student_data.get("Certifications", 0))]
    ]
    prof_table = Table(profile_data, colWidths=[135, 135, 135, 135])
    prof_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (0, -1), colors.HexColor('#f1f5f9')),
        ('BACKGROUND', (2, 0), (2, -1), colors.HexColor('#f1f5f9')),
        ('FONTNAME', (0, 0), (0, -1), 'Helvetica-Bold'),
        ('FONTNAME', (2, 0), (2, -1), 'Helvetica-Bold'),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#e2e8f0')),
        ('PADDING', (0, 0), (-1, -1), 6),
    ]))
    story.append(prof_table)
    story.append(Spacer(1, 15))

    # SHAP Factors
    story.append(Paragraph("Key Impact Factors (SHAP Analysis)", section_heading))
    pos_factors = prediction_res.get('top_positive_factors', [])
    neg_factors = prediction_res.get('top_negative_factors', [])

    pos_text = ", ".join([f"{f['feature']} (+{f['impact']})" for f in pos_factors]) if pos_factors else "Strong academic profile and core skills."
    neg_text = ", ".join([f"{f['feature']} ({f['impact']})" for f in neg_factors]) if neg_factors else "No major negative bottlenecks detected."

    shap_table_data = [
        [Paragraph("<b>Top Positive Drivers:</b>", styles['Normal']), Paragraph(f"<font color='#16a34a'>{pos_text}</font>", styles['Normal'])],
        [Paragraph("<b>Top Risk Factors:</b>", styles['Normal']), Paragraph(f"<font color='#dc2626'>{neg_text}</font>", styles['Normal'])]
    ]
    shap_table = Table(shap_table_data, colWidths=[150, 390])
    shap_table.setStyle(TableStyle([
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1')),
        ('PADDING', (0, 0), (-1, -1), 8),
    ]))
    story.append(shap_table)
    story.append(Spacer(1, 15))

    # Recommendations
    story.append(Paragraph("Actionable Improvement Recommendations", section_heading))
    suggestions = prediction_res.get('suggestions', [])
    for idx, sugg in enumerate(suggestions, 1):
        story.append(Paragraph(f"• <b>Step {idx}:</b> {sugg}", styles['Normal']))
        story.append(Spacer(1, 4))

    doc.build(story)
    logger.info(f"Generated individual prediction PDF at {output_filepath}")
    return output_filepath
